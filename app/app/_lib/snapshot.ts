/** /api/baskets/:id shape */
export function snapshotBasketGetResponse(id: string) {
  const basket = SNAPSHOT_BASKETS.find((b) => b.id === id);
  if (!basket) return null;
  const legs = SNAPSHOT_LEGS.filter((l) => l.basket_id === id);
  return {
    basket,
    legs,
    nav: basket.nav,
    breakdown: {
      basket_id: basket.id,
      nav: basket.nav,
      legs_resolved: 0,
      legs_total: legs.length,
      contributions: [],
    },
  };
}

/** /api/baskets/:id/nav shape */
export function snapshotBasketNavResponse(id: string) {
  const history = SNAPSHOT_NAV_HISTORY[id] ?? [];
  return { history };
}

// Scanner client-side filter + group helper. Mirrors the backend
// view: 'category_grouped' layout when no search query is provided,
// and falls back to a flat search-style response otherwise.
const ZONE_LIKE = (p: number): 0 | 1 | 2 | 3 | 4 => {
  if (!Number.isFinite(p)) return 0;
  if (p >= 0.85) return 3;
  if (p >= 0.50) return 4;
  if (p >= 0.15) return 2;
  return 1;
};

function toScannerRow(m: SnapshotMarket) {
  const rawEdge = m.raw_edge ?? null;
  return {
    question: m.question,
    source: m.source,
    marketId: m.condition_id,
    outcomeLabel: 'YES',
    p_market: m.p_market,
    p_model: m.p_model,
    edge: rawEdge,
    raw_edge: rawEdge,
    adjusted_edge: rawEdge,
    signal: m.signal,
    volume: m.volume ?? undefined,
    daysToClose: m.days_to_close ?? null,
    category: m.category,
    screened: true,
    excluded: false,
    impossible: false,
    is_tournament_market: m.is_tournament_market,
    is_favorite: m.is_favorite,
    normalized_p_market: m.is_tournament_market ? m.p_market : null,
    zone: ZONE_LIKE(m.p_market),
    include_in_basket: false,
  };
}

/** /api/scanner/markets shape with client-side search and grouping. */
export function snapshotScannerResponse(opts: {
  min?: number;
  max?: number;
  sort?: 'volume' | 'edge' | 'days' | 'p_market';
  search?: string;
  limit?: number;
} = {}) {
  const min = opts.min ?? 0.02;
  const max = opts.max ?? 0.15;
  const sort = opts.sort ?? 'volume';
  const search = (opts.search ?? '').trim().toLowerCase();

  // p_market window only applies when no search; explicit search should
  // see every snapshot row so the search bar feels complete.
  let pool: SnapshotMarket[] = search
    ? SNAPSHOT_MARKETS
    : SNAPSHOT_MARKETS.filter((m) => m.p_market >= min && m.p_market <= max);

  if (search) {
    pool = pool.filter((m) => m.question.toLowerCase().includes(search));
  }

  const rows = pool.map(toScannerRow);

  const sortFn: Record<string, (a: any, b: any) => number> = {
    volume: (a, b) => (b.volume ?? 0) - (a.volume ?? 0),
    edge: (a, b) => Math.abs(b.raw_edge ?? 0) - Math.abs(a.raw_edge ?? 0),
    days: (a, b) => (a.daysToClose ?? 9e9) - (b.daysToClose ?? 9e9),
    p_market: (a, b) => (a.p_market ?? 0) - (b.p_market ?? 0),
  };
  rows.sort(sortFn[sort] ?? sortFn.volume);
  if (opts.limit != null) rows.length = Math.min(rows.length, opts.limit);

  // Category-grouped view (default, no search): top 5 per category, mirroring
  // the live backend's layout hint.
  let groups:
    | Array<{
        category: string;
        short_count: number;
        long_count: number;
        long_section_start: number | null;
        markets: typeof rows;
      }>
    | undefined;
  const view: 'category_grouped' | 'search' = search ? 'search' : 'category_grouped';
  if (view === 'category_grouped') {
    const byCat: Record<string, typeof rows> = {};
    for (const r of rows) {
      const cat = (r.category ?? 'other').toLowerCase();
      if (!byCat[cat]) byCat[cat] = [];
      if (byCat[cat].length < 5) byCat[cat].push(r);
    }
    const ORDER = ['politics', 'crypto', 'macro', 'culture', 'sports', 'other'];
    groups = ORDER.filter((c) => byCat[c]?.length).map((cat) => {
      const markets = byCat[cat];
      const shortN = markets.filter((m: any) => m.signal === 'short' || m.signal === 'strong_short').length;
      const longN = markets.filter((m: any) => m.signal === 'long' || m.signal === 'strong_long').length;
      return {
        category: cat,
        short_count: shortN,
        long_count: longN,
        long_section_start: longN > 0 ? shortN : null,
        markets,
      };
    });
  }

  return {
    at: SNAPSHOT_AT_MS,
    count: rows.length,
    watched_count: SNAPSHOT_STATS.markets_tracked,
    counts: {
      polymarket: SNAPSHOT_STATS.polymarket_count,
      kalshi: SNAPSHOT_STATS.kalshi_count,
    },
    kalshi_error: null as string | null,
    kalshi_throttled: false,
    sort,
    search: search || null,
    total_after_filter: rows.length,
    view,
    groups,
    rows,
  };
}
